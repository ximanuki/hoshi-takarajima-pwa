/**
 * Product catalogue of the fictional wholesaler 架空商事 (包装資材・工場用消耗品の卸売).
 *
 * Each family is a name template with variant dimensions. A dimension value is
 * [label, price factor, unit override?, quantity factor?]. SKUs are the cartesian
 * product of the dimensions; the generator keeps `target` of them per category.
 * Canonical names use ASCII punctuation so that NFKC leaves them unchanged.
 */

export type DimValue = [label: string, factor: number, unit?: string, qtyFactor?: number];

export type Family = {
  name: string;
  unit: string;
  base: number;
  qty: [number, number];
  supplier: string;
  dims: DimValue[][];
  /** Index of a size dimension whose label becomes a code suffix (GL-2101-M). */
  sizeSuffix?: number;
};

export type Category = {
  code: string;
  name: string;
  target: number;
  /** 原価構成比 (原材料, 労務費, エネルギー, その他) in percent. */
  shares: [number, number, number, number];
  material: string;
  /** Past revision on 2025-04-01: supplier cost increase and list price increase (percent). */
  rev1: { cost: number; price: number } | null;
  families: Family[];
};

