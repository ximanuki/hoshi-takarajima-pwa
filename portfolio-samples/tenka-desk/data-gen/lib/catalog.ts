/** Linearly growing factors: start, start+step, ... */
function L(labels: string[], start: number, step: number): DimValue[] {
  return labels.map((l, i) => [l, Math.round((start + i * step) * 1000) / 1000]);
}
/** Same factor for every label (size dimensions). */
function S(labels: string[]): DimValue[] {
  return labels.map((l) => [l, 1]);
}
function P(pairs: DimValue[]): DimValue[] {
  return pairs;
}

