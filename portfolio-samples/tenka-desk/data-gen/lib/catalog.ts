export type Variant = {
  cat: Category;
  family: Family;
  familyIndex: number;
  values: DimValue[];
  name: string;
  unit: string;
  factor: number;
  qtyFactor: number;
  sizeLabel: string | null;
  /** Key of the variant without its size dimension (shares a base number). */
  groupKey: string;
};

/** Expand every family of a category into variants (deterministic order). */
export function expandCategory(cat: Category): Variant[] {
  const out: Variant[] = [];
  cat.families.forEach((family, familyIndex) => {
    let combos: DimValue[][] = [[]];
    for (const dim of family.dims) {
      const next: DimValue[][] = [];
      for (const c of combos) for (const v of dim) next.push([...c, v]);
      combos = next;
    }
    for (const values of combos) {
      let name = family.name;
      let factor = 1;
      let unit = family.unit;
      let qtyFactor = 1;
      values.forEach((v, i) => {
        name = name.replace(`{${i}}`, v[0]);
        factor *= v[1];
        if (v[2]) unit = v[2];
        if (v[3]) qtyFactor *= v[3];
      });
      const sizeLabel = family.sizeSuffix !== undefined ? values[family.sizeSuffix][0] : null;
      const groupKey = `${familyIndex}:${values.filter((_, i) => i !== family.sizeSuffix).map((v) => v[0]).join('/')}`;
      out.push({ cat, family, familyIndex, values, name, unit, factor, qtyFactor, sizeLabel, groupKey });
    }
  });
  return out;
}

